import type { EMRStore } from './types';

export type VerificationStatus = 'Verified' | 'Pending Verification' | 'Not Applicable';
export type ComplianceStatus = 'Passed' | 'Partial' | 'Failed' | 'Not Tested' | 'Pending Verification' | 'Not Applicable';
export type RequirementCategory = 'Mandatory NABH Requirement' | 'Core Standard' | 'Commitment to Excellence' | 'Internal Hospital Policy' | 'Digital Feature / Recommendation';

export interface NABHChapter {
  code: string;
  name: string;
  category: 'Patient-Centered' | 'Organization-Centered';
  edition5StandardsCount: number;
  edition4StandardsCount: number;
  description: string;
}

export interface NABHStandard {
  standardCode: string; // e.g. AAC.1, AAC.2, COP.6
  chapterCode: string;
  chapterName: string;
  titleEdition5: string;
  titleEdition4: string;
  edition5Code: string;
  edition4Code: string;
  edition5ObjectiveElementsCount: number;
  edition4ObjectiveElementsCount: number;
  requirementSummary: string;
  applicability: string;
  documentTitle: string;
  documentSection: string;
  pageNumber: string;
  sourceUrl: string;
  verificationStatus: VerificationStatus;
  effectiveDateEdition5: string;
  effectiveDateEdition4: string;
}

export interface NABHObjectiveElement {
  oeCode: string; // e.g. AAC.2.b, COP.6.a
  standardCode: string;
  chapterCode: string;
  edition: '5th Edition' | '4th Edition' | 'Both';
  title: string;
  description: string;
  category: RequirementCategory;
  evidenceRequired: string;
  auditTrailRequired: boolean;
  verificationStatus: VerificationStatus;
}

